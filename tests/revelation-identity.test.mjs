import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { buildWorldModel } from '../js/features/pixel-bible/world.js';
import { isMentionOnlyPerson } from '../js/features/pixel-bible/mention-only.js';
import { resolveIdentity } from '../js/features/pixel-bible/identity.js';

test('요한계시록은 상징적 인물·집단·영적 존재와 실제 인용 인물을 구분한다',async()=>{
 const rev=JSON.parse(await fs.promises.readFile(new URL('../data/summary/rev.json',import.meta.url),'utf8'));
 const eventBook=JSON.parse(await fs.promises.readFile(new URL('../data/pixel-bible/events/rev.json',import.meta.url),'utf8'));
 assert.equal(resolveIdentity('어린 양',{code:'rev',chapter:5}).id,resolveIdentity('예수',{code:'rev',chapter:22}).id);
 assert.equal(resolveIdentity('백마 탄 자',{code:'rev',chapter:19}).id,resolveIdentity('어린 양',{code:'rev',chapter:19}).id);
 assert.equal(resolveIdentity('붉은 용',{code:'rev',chapter:12}).id,resolveIdentity('사탄',{code:'rev',chapter:12}).id);
 assert.equal(resolveIdentity('바다에서 나온 짐승',{code:'rev',chapter:13}).id,resolveIdentity('짐승',{code:'rev',chapter:20}).id);
 assert.equal(resolveIdentity('거짓 선지자',{code:'rev',chapter:20}).id,resolveIdentity('땅에서 올라온 짐승',{code:'rev',chapter:13}).id);
 assert.notEqual(resolveIdentity('짐승',{code:'rev',chapter:20}).id,resolveIdentity('거짓 선지자',{code:'rev',chapter:20}).id);
 assert.equal(resolveIdentity('보좌에 앉으신 이',{code:'rev',chapter:5}).id,resolveIdentity('하나님',{code:'rev',chapter:5}).id);
 assert.equal(resolveIdentity('큰 음녀',{code:'rev',chapter:17}).id,resolveIdentity('바벨론',{code:'rev',chapter:18}).id);
 assert.equal(resolveIdentity('새 예루살렘',{code:'rev',chapter:21}).id,resolveIdentity('어린 양의 아내',{code:'rev',chapter:19}).id);
 assert.equal(resolveIdentity('해를 옷 입은 여자',{code:'rev',chapter:12}).kind,'group');
 assert.equal(resolveIdentity('네 생물',{code:'rev',chapter:4}).kind,'spiritual');
 assert.equal(resolveIdentity('황충',{code:'rev',chapter:9}).kind,'group');
 assert.equal(resolveIdentity('다섯째 천사',{code:'rev',chapter:9}).kind,'spiritual');
 assert.equal(resolveIdentity('요한',{code:'rev',chapter:22}).id,resolveIdentity('요한',{code:'jhn',chapter:21,role:'예수께서 사랑하시는 제자'}).id);
 assert.equal(resolveIdentity('안디바',{code:'rev',chapter:2}).id,'person:antipas-pergamum');
 assert.equal(resolveIdentity('니골라당',{code:'rev',chapter:2}).kind,'group');
 assert.equal(resolveIdentity('사탄의 회당',{code:'rev',chapter:3}).kind,'group');
 assert.equal(resolveIdentity('이십사 장로',{code:'rev',chapter:19}).kind,'spiritual');
 assert.equal(resolveIdentity('흰 말 탄 자',{code:'rev',chapter:6}).kind,'person');
 assert.equal(resolveIdentity('흰 말 탄 자',{code:'rev',chapter:6}).id,resolveIdentity('백마 탄 자',{code:'rev',chapter:19}).id,'요한계시록 6장의 첫 흰 말 기사는 본문 해설의 주된 개혁주의 해석을 따라 그리스도와 통합');
 assert.ok(isMentionOnlyPerson({name:'발람'},{code:'rev',chapter:2}));
 assert.ok(isMentionOnlyPerson({name:'모세'},{code:'rev',chapter:15}));
 for(const chapter of [3,5])assert.ok(isMentionOnlyPerson({name:'다윗'},{code:'rev',chapter}));
 assert.ok(isMentionOnlyPerson({name:'다윗'},{code:'rev',chapter:22}));
 assert.ok(!rev.chapters['15'].rels.some(r=>r.to==='모세'),'모세의 노래는 노래 제목·전승의 언급이지 모세와의 직접 상호작용이 아님');
 assert.ok(!rev.chapters['20'].people.some(p=>p.name==='짐승과 거짓 선지자'));
 assert.ok(!rev.chapters['19'].people.some(p=>p.name==='이십사 장로와 네 생물'));
 assert.ok(rev.chapters['6'].rels.some(r=>r.from==='네 생물'&&r.to==='붉은 말 탄 자'&&r.verses==='3'));
 assert.ok(!rev.chapters['6'].rels.some(r=>r.from==='붉은 말 탄 자'&&r.to==='순교한 영혼들'),'순교한 영혼들을 특정 말 탄 자가 죽였다고 연결하지 않음');
 assert.ok(rev.chapters['7'].rels.some(r=>r.from==='십사만 사천'&&r.to==='큰 무리'&&r.verses==='4, 9'),'본문 해설의 주된 개혁주의 무천년 관점에서 땅의 교회와 하늘의 승리한 교회를 연결');
 assert.ok(rev.chapters['8'].rels.some(r=>r.from==='향로를 든 천사'&&r.to==='하나님'&&r.verses==='3-4'));
 assert.ok(rev.chapters['8'].rels.some(r=>r.from==='하나님'&&r.to==='성도들'&&r.verses==='3-5'),'기도를 들으시는 분과 기도하는 성도의 관계를 기록하되 천사가 불을 던진 행동은 구분');
 assert.ok(!rev.chapters['10'].rels.some(r=>r.from==='하나님'&&r.to==='요한'&&r.verses==='11'),'발화자가 특정되지 않은 마지막 명령을 하나님께 단정 귀속하지 않음');
 assert.ok(rev.chapters['14'].rels.some(r=>r.from==='성령'&&r.to==='죽은 성도들'&&r.verses==='13'));
 assert.ok(!rev.chapters['14'].rels.some(r=>r.from==='인자 같은 이'&&r.to==='십사만 사천'),'곡식 추수를 십사만 사천 명에 한정하지 않음');
 assert.equal(resolveIdentity('더러운 세 영',{code:'rev',chapter:16}).kind,'spiritual');
 for(const from of ['용','짐승','거짓 선지자'])assert.ok(rev.chapters['16'].rels.some(r=>r.from===from&&r.to==='더러운 세 영'&&r.verses==='13-14'));
 assert.ok(rev.chapters['16'].rels.some(r=>r.from==='더러운 세 영'&&r.to==='천하 왕들'&&r.verses==='14-16'));
 assert.ok(!rev.chapters['20'].rels.some(r=>r.from==='보좌에 앉으신 이'&&['짐승','거짓 선지자'].includes(r.to)&&r.verses==='10'));
 const rev16=buildWorldModel([{code:'rev',name:'요한계시록',chap:16,data:{...rev.chapters['16'],eventScenes:eventBook.scenes.filter(s=>s.chapter===16)}}]);
 assert.ok(!rev16.cast.some(p=>p.name==='개구리'),'개구리 같은 악한 영을 동물 NPC로 생성하지 않음');
 const rev12=buildWorldModel([{code:'rev',name:'요한계시록',chap:12,data:{...rev.chapters['12'],eventScenes:eventBook.scenes.filter(s=>s.chapter===12)}}]);
 const dragonScene=rev12.scenes.find(s=>s.sourceUnits?.includes('rev.12.0'));
 assert.equal(dragonScene?.animation?.lead,'사탄','장면 별칭과 정규 신원 통합 뒤에도 장면 동작을 유지');
 assert.ok(rev.chapters['20'].rels.some(r=>r.from==='짐승'&&r.to==='거짓 선지자'&&r.verses==='10'));
 for(const chapter of [5,6,13])assert.ok(!eventBook.additionalPeople?.[String(chapter)]?.some(p=>p.name==='누가'),'본문 의문사 "누가"를 복음서 저자 누가로 오인하지 않음');
 for(const chapter of [3,5]){
  assert.ok(eventBook.additionalPeople?.[String(chapter)]?.some(p=>p.name==='다윗'),'다윗 언급의 근거는 유지');
  const model=buildWorldModel([{code:'rev',name:'요한계시록',chap:chapter,data:{...rev.chapters[String(chapter)],eventScenes:eventBook.scenes.filter(s=>s.chapter===chapter),additionalPeople:eventBook.additionalPeople[String(chapter)]}}]);
  assert.ok(!model.cast.some(p=>p.name==='다윗'),'다윗은 직접 등장하는 배우가 아니라 과거 인용 인물');
 }
});
